function form(old){

  const x=old
    ? {
        ...old,
        spezzoni:[...old.spezzoni]
      }
    : {
        id:Math.max(
          0,
          ...data.map(a=>a.id)
        )+1,
        sherwin:"",
        interno:"",
        descrizione:"",
        ubicazione:"",
        spezzoni:[]
      };

  $("#modalRoot").innerHTML=`

    <div class="modalShade" id="shade">

      <section class="modal">

        <div class="grab"></div>

        <div class="modalHead">

          <div>

            <div class="eyebrow">
              ${old?"Modifica":"Nuova"}
            </div>

            <h1
              class="title"
              style="font-size:27px"
            >
              Scheda materia prima
            </h1>

          </div>

          <button
            class="close"
            id="cx"
          >
            ×
          </button>

        </div>

        <form
          class="form"
          id="fm"
        >

          <label class="modalLabel">

            Codice Sherwin-Williams

            <input
              class="input"
              name="sherwin"
              value="${esc(x.sherwin)}"
              required
            >

          </label>

          <label class="modalLabel">

            Codice Interno

            <input
              class="input"
              name="interno"
              value="${esc(x.interno)}"
            >

          </label>

          <label class="modalLabel">

            Descrizione

            <textarea
              class="textarea"
              name="descrizione"
              required
            >${esc(x.descrizione)}</textarea>

          </label>

          <label class="modalLabel">

            Reparto / Zona Stock

            <input
              class="input"
              name="ubicazione"
              value="${esc(x.ubicazione)}"
            >

          </label>

          <div class="modalLabel">
            Spezzoni
          </div>

          <div id="sps">

            ${
              x.spezzoni
                .map(z=>`
                  <div class="spezzoneRow">

                    <input
                      class="input sp"
                      value="${esc(z)}"
                    >

                    <button
                      type="button"
                      class="remove"
                      data-rm
                    >
                      ×
                    </button>

                  </div>
                `)
                .join("")
            }

          </div>

          <button
            type="button"
            class="addLine"
            id="asp"
          >
            ＋ Aggiungi spezzone
          </button>

          <button
            class="action primary"
            type="submit"
            style="margin-top:8px"
          >
            Salva scheda
          </button>

        </form>

      </section>

    </div>
  `;

  $("#cx").onclick=closeModal;

  $("#shade").onclick=e=>{
    if(e.target.id==="shade"){
      closeModal();
    }
  };

  const rm=()=>
    $$("[data-rm]").forEach(b=>{
      b.onclick=()=>{
        b.parentElement.remove();
      };
    });

  $("#asp").onclick=()=>{

    $("#sps").insertAdjacentHTML(
      "beforeend",
      `
        <div class="spezzoneRow">

          <input
            class="input sp"
          >

          <button
            type="button"
            class="remove"
            data-rm
          >
            ×
          </button>

        </div>
      `
    );

    rm();
  };

  rm();

  $("#fm").onsubmit=e=>{

    e.preventDefault();

    const f=new FormData(e.target);

    x.sherwin=
      f.get("sherwin").trim();

    x.interno=
      f.get("interno").trim();

    x.descrizione=
      f.get("descrizione").trim();

    x.ubicazione=
      f.get("ubicazione").trim();

    x.spezzoni=
      $$(".sp")
        .map(i=>i.value.trim())
        .filter(Boolean);

    const i=data.findIndex(
      a=>a.id===x.id
    );

    if(i<0){
      data.unshift(x);
    }else{
      data[i]=x;
    }

    save();
    closeModal();
    render();
  };
}

